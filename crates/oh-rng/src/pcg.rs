//! `pcg32_fast` — port of `ssvu::pcg32_fast` == `pcg_engines::mcg_xsh_rs_64_32`
//! from `extlibs/SSVUtils/include/SSVUtils/Internal/PCG/pcg_random.hpp`.
//!
//! Exact parameters (read from the header, do not "improve"):
//!
//! - state type (`itype`): `u64`; result type (`xtype`): `u32`
//! - kind: **MCG** (`no_stream` mixin): `increment() == 0`, `is_mcg == true`
//! - multiplier: `6364136223846793005`
//!   (`PCG_DEFINE_CONSTANT(uint64_t, default, multiplier, 6364136223846793005ULL)`)
//! - seeding (engine ctor, mcg branch): `state = seed | 3`
//! - output function: `xsh_rs` with itype=64/xtype=32:
//!   `opbits = 3`, `xshift = 22`, `bottomspare = 29`, `maxrandshift = 7`
//! - `output_previous == true` (`sizeof(itype) <= 8`): each call returns
//!   `output(previous_state)` and then advances `state = state * M`
//! - `advance(delta)`: Brown jump-ahead with `cur_plus = 0`
//!
//! Ground truth: `.agents/plans/001-rust-port/mapping/oracle-vectors.md`
//! (generated by the C++ build at commit 1e2cba71, `g++ -std=c++20`).

/// LCG multiplier, verbatim from `pcg_random.hpp` (`default_multiplier<u64>`).
pub const MULTIPLIER: u64 = 6364136223846793005;

/// `pcg32_fast`: 64-bit MCG state, 32-bit xsh_rs output.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub struct Pcg32Fast {
    state: u64,
}

impl Pcg32Fast {
    /// Engine ctor, mcg branch: `state_(this->is_mcg ? state | state_type(3U) : ...)`.
    pub const fn from_seed(seed: u64) -> Self {
        Self { state: seed | 3 }
    }

    /// C++ `min()` / `max()` of the engine (`result_type` = `u32`).
    pub const fn min() -> u32 {
        0
    }

    pub const fn max() -> u32 {
        u32::MAX
    }

    /// `operator()()`: with `output_previous == true`, returns the output of
    /// the *previous* state, then `state_ = bump(state_)` with
    /// `bump(state) = state * multiplier() + increment()` (increment is 0).
    pub fn next_u32(&mut self) -> u32 {
        let old = self.state;
        // increment() == 0 (no_stream / MCG): the additive term vanishes.
        self.state = old.wrapping_mul(MULTIPLIER);
        output_xsh_rs(old)
    }

    /// `void advance(itype delta)` — standard LCG jump-ahead with
    /// `cur_plus == 0` (MCG).
    pub fn advance(&mut self, delta: u64) {
        self.state = advance_mcg(self.state, delta);
    }

    /// `backstep(delta)` / `discard(delta)` are `advance(-delta)` /
    /// `advance(delta)` in C++; with unsigned `u64` delta, backstep is
    /// `advance(delta.wrapping_neg())` (the C++ comment notes a signed
    /// delta "just goes the long way round").
    pub fn backstep(&mut self, delta: u64) {
        self.advance(delta.wrapping_neg());
    }
}

/// `xsh_rs_mixin::output` instantiated with itype = `u64`, xtype = `u32`.
///
/// Header constants for this instantiation:
/// `bits = 64`, `xtypebits = 32`, `sparebits = 32`, `opbits = 3`,
/// `mask = 7`, `maxrandshift = 7`, `topspare = 3`, `bottomspare = 29`,
/// `xshift = topspare + (xtypebits + maxrandshift) / 2 = 3 + (32 + 7) / 2 = 22`.
fn output_xsh_rs(mut internal: u64) -> u32 {
    let rshift = (internal >> (64 - 3)) & 7; // top 3 bits, masked by `mask`
    internal ^= internal >> 22; // xshift
    (internal >> (29 - 7 + rshift)) as u32 // bottomspare - maxrandshift + rshift
}

/// `engine::advance` (Brown, "Random Number Generation with Arbitrary
/// Stride", 1994) as found in `pcg_random.hpp`, with `cur_plus == 0`:
///
/// ```text
/// acc_mult = 1; acc_plus = 0;
/// while (delta > 0) {
///     if (delta & 1) { acc_mult *= cur_mult; acc_plus = acc_plus * cur_mult + cur_plus; }
///     cur_plus = (cur_mult + 1) * cur_plus;   // stays 0
///     cur_mult *= cur_mult;
///     delta >>= 1;
/// }
/// return acc_mult * state + acc_plus;         // acc_plus is 0
/// ```
fn advance_mcg(state: u64, delta: u64) -> u64 {
    let mut acc_mult: u64 = 1;
    let mut cur_mult: u64 = MULTIPLIER;
    let mut d = delta;
    while d > 0 {
        if d & 1 != 0 {
            acc_mult = acc_mult.wrapping_mul(cur_mult);
        }
        // cur_plus is identically 0 for no_stream, so the acc_plus terms
        // from pcg_random.hpp are omitted (they contribute 0).
        cur_mult = cur_mult.wrapping_mul(cur_mult);
        d >>= 1;
    }
    state.wrapping_mul(acc_mult)
}
