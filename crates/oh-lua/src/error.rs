//! Error types, ported 1:1 from the `Lua::` exception hierarchy in
//! `include/SSVOpenHexagon/Utils/LuaWrapper.hpp` and the rc-mapping in its
//! `_call`/`_load` (mapping/lua-api.md §3.5).
//!
//! | C++ exception              | Rust variant                    | `what()`/Display text |
//! |----------------------------|---------------------------------|-----------------------|
//! | `ExecutionErrorException`  | `LuaError::ExecutionError`      | the Lua error message |
//! | `VariableDoesntExistException` | `LuaError::VariableDoesntExist` | `Variable "<name>" doesn't exist in lua context` |
//! | `SyntaxErrorException`     | `LuaError::SyntaxError`         | the Lua error message |
//! | `WrongTypeException`       | `LuaError::WrongType`           | `Trying to cast a lua variable to an invalid type` |
//! | `std::bad_alloc` (LUA_ERRMEM) | `LuaError::MemoryError`       | the Lua error message |
//!
//! The C++ "other rc" case (`std::runtime_error("UNKNOWN RC: " + msg)`) is
//! mapped to `ExecutionError` with the same `UNKNOWN RC: ` prefix.

use mlua::Error as MluaError;

#[derive(Debug, thiserror::Error)]
pub enum LuaError {
    /// Thrown when an error happens during execution (like not enough
    /// parameters for a function).
    #[error("{message}")]
    ExecutionError { message: String },

    /// Generated by `read_variable` when the asked variable doesn't exist /
    /// is nil. Message format matches the C++ constructor exactly.
    #[error("Variable \"{variable}\" doesn't exist in lua context")]
    VariableDoesntExist { variable: String },

    /// Thrown when a syntax error happens in a lua script.
    #[error("{message}")]
    SyntaxError { message: String },

    /// Thrown when trying to cast a lua variable to an invalid type
    /// (C++: the value is userdata).
    #[error("Trying to cast a lua variable to an invalid type")]
    WrongType,

    /// Analogue of `std::bad_alloc` for `LUA_ERRMEM` (C++ `_call`/`_load`
    /// throw `std::bad_alloc` directly, not a `Lua::` exception).
    #[error("{message}")]
    MemoryError { message: String },
}

impl LuaError {
    /// Maps an `mlua` error onto the C++ exception hierarchy.
    ///
    ///   * C++ `_call` rc mapping (LuaWrapper.cpp `_call`, `_load`):
    ///   * `LUA_ERRRUN`  -> `ExecutionErrorException(msg)`
    ///   * `LUA_ERRSYNTAX` -> `SyntaxErrorException(msg)`
    ///   * `LUA_ERRMEM`  -> `std::bad_alloc`
    ///   * anything else -> `std::runtime_error("UNKNOWN RC: " + msg)`
    #[must_use]
    pub fn from_mlua(err: MluaError) -> Self {
        match err {
            MluaError::SyntaxError { message, .. } => LuaError::SyntaxError {
                message: message.clone(),
            },
            MluaError::MemoryError(message) => LuaError::MemoryError {
                message: message.clone(),
            },
            MluaError::RuntimeError(message) => LuaError::ExecutionError {
                message: message.clone(),
            },
            // C++: any other pcall/load rc -> runtime_error("UNKNOWN RC: ...")
            other => LuaError::ExecutionError {
                message: format!("UNKNOWN RC: {other}"),
            },
        }
    }
}
